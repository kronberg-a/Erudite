assert.equal(await frame.evaluate(()=>repertoire.white[0].category),'Edited opening');
console.log('PASS: create/edit/save opening');
await page.getByRole('button',{name:'Import',exact:true}).click();
await frame.locator('#import-category-input').fill('PGN variations');
await frame.locator('#import-pgn-input').fill('1. d4 d5 2. c4 (2. Nf3 Nf6) e6 *');
await frame.waitForFunction(()=>parsedImportLines.length>=2);
await frame.locator('#import-execute-btn').click();
assert.ok(await frame.evaluate(()=>repertoire.white.length>=3));
console.log('PASS: PGN variations imported');
await frame.evaluate(()=>openSettings());
const downloadPromise=page.waitForEvent('download');
await frame.getByRole('button',{name:'PGN exportieren',exact:true}).click();
const download=await downloadPromise;assert.equal(download.suggestedFilename(),'erudite-repertoire.pgn');
console.log('PASS: PGN export download');
await page.getByRole('button',{name:'Dark',exact:true}).click();
await frame.waitForFunction(()=>document.documentElement.classList.contains('dark'));
await frame.locator('#setting-theme-row').click();
await page.waitForFunction(()=>!document.documentElement.classList.contains('dark'));
console.log('PASS: bidirectional theme sync');
const explorerSources=[];
await page.route('https://explorer.lichess.org/**',async route=>{
 assert.equal(route.request().headers().authorization,'Bearer test-only-token');
 explorerSources.push(new URL(route.request().url()).pathname);
 await route.fulfill({json:{white:100,draws:50,black:80,moves:[{san:'Nc6',uci:'b8c6',white:100,draws:50,black:80}]}});
});
await frame.evaluate(()=>{closeSettings();editLine(repertoire.white[0].id)});
await frame.locator('#explorer-api-token').fill('test-only-token');
await frame.locator('#explorer-api-token').dispatchEvent('change');
await frame.waitForFunction(()=>document.querySelectorAll('#explorer-moves .explorer-move').length>0);
console.log('PASS: authenticated Lichess query and rendered response (fixture)');
await frame.locator('#explorer-source-select').selectOption('masters');
await frame.waitForFunction(()=>document.querySelectorAll('#explorer-moves .explorer-move').length>0);
assert.ok(explorerSources.includes('/masters'));console.log('PASS: authenticated masters query and rendered response (fixture)');
await frame.evaluate(()=>{userSettings.analysisOpen=false;cancelAdd();startBotSetup(repertoire.white[0].id);botElo=500;selectBotStyle('tactical');launchBotGame()});
await frame.waitForFunction(()=>game.history().length>=4,{timeout:60000});
console.log('PASS: Stockfish bot played legal reply',await frame.evaluate(()=>game.pgn()));
const fen=await frame.evaluate(()=>game.fen());
await page.getByRole('button',{name:'Words',exact:true}).first().click();
await frame.waitForFunction(()=>!eruditeActive);
