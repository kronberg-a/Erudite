await page.waitForTimeout(500);
assert.equal(await frame.evaluate(()=>game.fen()),fen);
assert.equal(await frame.evaluate(()=>engineCalculating),false);
await page.getByRole('button',{name:'Chess',exact:true}).first().click();
await frame.waitForFunction(()=>eruditeActive);
assert.equal(await frame.evaluate(()=>game.fen()),fen);
console.log('PASS: Words/Chess sessions retained and engine paused');
await frame.evaluate(()=>{stopBotGame();closeBotResults();editLine(repertoire.white[0].id);analysisDepth=12;analysisLines=2;toggleAnalysisMenu()});
await frame.waitForFunction(()=>analysisResults.filter(Boolean).length===2 && document.querySelector('[data-engine-suggestion]'));
console.log('PASS: MultiPV analysis, evaluation and best-move arrow');
await frame.evaluate(()=>cancelAdd());
for (const [elo,style] of [[1500,'greedy'],[2500,'positional'],[3300,'neutral']]) {
 await frame.evaluate(({elo,style})=>{botElo=elo;selectBotStyle(style);launchBotGame()}, {elo,style});
 if (elo === 3300) {
  await frame.waitForFunction(()=>engineCalculating);
  await page.getByRole('button',{name:'Words',exact:true}).first().click();
  await frame.waitForFunction(()=>!eruditeActive);
  const pausedFen=await frame.evaluate(()=>game.fen());
  await page.waitForTimeout(1000);
  assert.equal(await frame.evaluate(()=>game.fen()),pausedFen);
  assert.equal(await frame.evaluate(()=>engineCalculating),false);
  await page.getByRole('button',{name:'Chess',exact:true}).first().click();
 }
 await frame.waitForFunction(()=>game.history().length>=4);
 await frame.waitForFunction(()=>!isBotThinking);
 await frame.evaluate(()=>{stopBotGame();closeBotResults()});
 console.log(`PASS: ${elo} ${style} bot${elo===3300?' with in-flight pause/resume':''}`);
}
await frame.evaluate(()=>openSelectionMode());
await frame.getByRole('button',{name:'Starten',exact:true}).click();
await frame.waitForFunction(()=>mode==='train');
await frame.evaluate(()=>{const move=game.move(currentTrainLine.moveHistory[currentMoveIndex]);handleTrainingMove(move)});
await frame.waitForFunction(()=>game.history().length>=2);
console.log('PASS: repertoire training replies');
await frame.evaluate(()=>stopTraining());
await page.screenshot({path:'test-results/chess-desktop.png'});
