await page.waitForTimeout(300);
await page.screenshot({path:'test-results/chess-mobile.png'});
console.log('MOBILE',await frame.evaluate(()=>({board:document.getElementById('board').getBoundingClientRect().toJSON(),scroll:document.documentElement.scrollWidth,width:innerWidth})));
assert.equal(await frame.evaluate(()=>document.documentElement.scrollWidth),390);
assert.ok(await frame.locator('#board').isVisible());
assert.deepEqual(errors,[]);
await page.getByRole('button',{name:'Dark',exact:true}).click();
await frame.waitForFunction(()=>document.documentElement.classList.contains('dark'));
