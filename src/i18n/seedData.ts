const ipa: Partial<Record<Language, string>> = {
  en: "/ˌpɒsəˈbɪləti/",
  de: "/ˈmøːklɪçkaɪt/",
  fr: "/pɔ.si.bi.li.te/",
  ru: "/vɐzˈmoʐnəsʲtʲ/",
  it: "/possibiliˈta/",
  es: "/posibiliˈðað/",
};
export function seedPair(source: Language, target: Language): PairData {
  return {
    categories: structuredClone(seedCategories),
    words: concepts.map(([category, words, examples], index) => ({
      id: `${source}-${target}-${index}`,
      targetWord: words[target],
      transcription: index === 0 ? ipa[target] : undefined,
      translations: [words[source]],
      examples: [
        {
          targetSentence: examples[target],
          translatedSentence: examples[source],
        },
      ],
      categoryIds: [category],
      status: "NEW",
      step: 0,
      repCount: 0,
      lastReviewedOrder: 0,
      createdAt: Date.now(),
    })),
  };
}
